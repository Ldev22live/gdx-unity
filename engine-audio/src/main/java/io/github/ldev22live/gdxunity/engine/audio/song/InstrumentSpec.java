package io.github.ldev22live.gdxunity.engine.audio.song;

import com.badlogic.gdx.utils.JsonValue;
import io.github.ldev22live.gdxunity.engine.audio.SfxrParams;
import io.github.ldev22live.gdxunity.engine.audio.SynthPatch;

import java.util.Locale;
import java.util.Objects;

/** What a channel plays: the settings from which a {@link io.github.ldev22live.gdxunity.engine.audio.Instrument} is built. */
public final class InstrumentSpec {
    /** Kinds of instrument. */
    public enum Type {
        /** The built-in synthesizer ({@link #patch}). */
        SYNTH,
        /** The generated drum kit; each drum answers to its General MIDI note. */
        DRUMS,
        /** A WAV file ({@link #path}) pitched across the keyboard from {@link #rootNote}. */
        SAMPLE,
        /** A sound generated by sfxr ({@link #sfxr}), played like a sample. */
        SFXR,
        /** A preset of an .sf2 file ({@link #path}, {@link #bank}, {@link #program}). */
        SOUNDFONT
    }

    public Type type = Type.SYNTH;
    /** Settings for {@link Type#SYNTH}. */
    public SynthPatch patch = new SynthPatch();
    /** Settings for {@link Type#SFXR}. */
    public SfxrParams sfxr = SfxrParams.preset("Coin");
    /** Project-relative file for {@link Type#SAMPLE} and {@link Type#SOUNDFONT}. */
    public String path = "";
    /** Note at which a sample plays unchanged. */
    public int rootNote = 60;
    /** True when a sample plays to its end whatever the note length. */
    public boolean oneShot;
    public int bank;
    public int program;

    public static InstrumentSpec synth(SynthPatch patch) {
        InstrumentSpec spec = new InstrumentSpec();
        spec.type = Type.SYNTH;
        spec.patch = Objects.requireNonNull(patch, "patch cannot be null");
        return spec;
    }

    public static InstrumentSpec drums() {
        InstrumentSpec spec = new InstrumentSpec();
        spec.type = Type.DRUMS;
        return spec;
    }

    public static InstrumentSpec sample(String path) {
        InstrumentSpec spec = new InstrumentSpec();
        spec.type = Type.SAMPLE;
        spec.path = Objects.requireNonNull(path, "path cannot be null");
        return spec;
    }

    public static InstrumentSpec sfxr(SfxrParams params) {
        InstrumentSpec spec = new InstrumentSpec();
        spec.type = Type.SFXR;
        spec.sfxr = Objects.requireNonNull(params, "params cannot be null");
        spec.oneShot = true;
        return spec;
    }

    public static InstrumentSpec soundFont(String path, int bank, int program) {
        InstrumentSpec spec = new InstrumentSpec();
        spec.type = Type.SOUNDFONT;
        spec.path = Objects.requireNonNull(path, "path cannot be null");
        spec.bank = bank;
        spec.program = program;
        return spec;
    }

    /** A copy that can be edited without touching this spec. */
    public InstrumentSpec copy() {
        InstrumentSpec c = new InstrumentSpec();
        c.type = type;
        c.patch = patch.copy();
        c.sfxr = sfxr.copy();
        c.path = path;
        c.rootNote = rootNote;
        c.oneShot = oneShot;
        c.bank = bank;
        c.program = program;
        return c;
    }

    /** JSON object text. */
    public String toJson() {
        return String.format(Locale.ROOT,
            "{\"type\":\"%s\",\"path\":%s,\"rootNote\":%d,\"oneShot\":%s,\"bank\":%d,\"program\":%d,\"patch\":%s,\"sfxr\":%s}",
            type, SongIO.quote(path), rootNote, oneShot, bank, program, patch.toJson(), sfxr.toJson());
    }

    /** Reads what {@link #toJson()} wrote. */
    public static InstrumentSpec fromJson(JsonValue json) {
        InstrumentSpec spec = new InstrumentSpec();
        spec.type = Type.valueOf(json.getString("type", Type.SYNTH.name()));
        spec.path = json.getString("path", "");
        spec.rootNote = json.getInt("rootNote", 60);
        spec.oneShot = json.getBoolean("oneShot", false);
        spec.bank = json.getInt("bank", 0);
        spec.program = json.getInt("program", 0);
        if (json.has("patch")) {
            spec.patch = SynthPatch.fromJson(json.get("patch"));
        }
        if (json.has("sfxr")) {
            spec.sfxr = SfxrParams.fromJson(json.get("sfxr"));
        }
        return spec;
    }
}
