import { isVec3, parseGraph, serializeGraph, type Graph, type Literal } from "./graph";

/**
 * Carries a graph inside the source generated from it, so Java, Kotlin and TypeScript scripts can travel between the
 * desktop and the web editor (TD-045). The graph is the `.graph` JSON as base64 in `//` comment lines at the end of the
 * file, which all three languages accept; the desktop editor writes and reads the same block (`GraphSourceEmbed`).
 * Only the embedded graph is read back: edits made to the code itself are not converted.
 */

/** First line of the block; the version lets a later format change be told apart. */
export const EMBED_BEGIN = "// forgeroom-graph:begin v1";
/** Last line of the block. */
export const EMBED_END = "// forgeroom-graph:end";
/** Base64 characters per comment line. */
const LINE_WIDTH = 100;

function toBase64(text: string): string {
  const bytes = new TextEncoder().encode(text);
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary);
}

function fromBase64(encoded: string): string {
  const binary = atob(encoded);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return new TextDecoder("utf-8", { fatal: true }).decode(bytes);
}

/**
 * The desktop editor stores a float as the double it widens to (0.8f is written as 0.800000011920929). A number that is
 * exactly a 32-bit float is turned back into the shortest text that reads as the same float, so an imported graph shows
 * 0.8 and generates `0.8`. Other numbers (a web-authored 0.8 is not exactly a float) are left alone.
 */
export function narrowFloat(value: number): number {
  if (!Number.isFinite(value) || Math.fround(value) !== value) return value;
  for (let digits = 1; digits <= 9; digits++) {
    const candidate = Number(value.toPrecision(digits));
    if (Math.fround(candidate) === value) return candidate;
  }
  return value;
}

function narrowLiteral<T extends Literal | null>(value: T): T {
  if (typeof value === "number") return narrowFloat(value) as T;
  if (isVec3(value)) return { x: narrowFloat(value.x), y: narrowFloat(value.y), z: narrowFloat(value.z) } as T;
  return value;
}

/** `source` with the block for `graph` appended. */
export function appendGraph(source: string, graph: Graph): string {
  const encoded = toBase64(serializeGraph(graph));
  const lines = [
    "",
    "// The block below lets Forgeroom (desktop or web) turn this script back into a graph. Keep it to be able to",
    "// import the script into the other editor; changes made to the code above are not read back.",
    EMBED_BEGIN,
  ];
  for (let i = 0; i < encoded.length; i += LINE_WIDTH) lines.push(`// ${encoded.slice(i, i + LINE_WIDTH)}`);
  lines.push(EMBED_END, "");
  return (source.endsWith("\n") ? source : `${source}\n`) + lines.join("\n");
}

/** A line of a script that is not what its embedded graph generates; {@code line} counts from 1. */
export interface ScriptEdit {
  line: number;
  text: string;
}

/**
 * Finds the first place where `source` differs from `generated`, the script the embedded graph generates now (TD-065, part B). Importing reads
 * only the embedded graph, so a line changed by hand is not read back; this tells the user which line. Line endings, trailing spaces and the
 * final newline do not count. The same rules as the desktop's `GraphSourceEmbed.findEdit`.
 *
 * @returns the first difference, or null when the two are the same
 */
export function findEdit(source: string, generated: string): ScriptEdit | null {
  const lines = (text: string): string[] => text.replace(/\r\n/g, "\n").trimEnd().split("\n");
  const actual = lines(source);
  const expected = lines(generated);
  const shared = Math.min(actual.length, expected.length);
  for (let i = 0; i < shared; i++) {
    if (actual[i]!.trimEnd() !== expected[i]!.trimEnd()) return { line: i + 1, text: actual[i]!.trim() };
  }
  if (actual.length > expected.length) return { line: shared + 1, text: `(an extra line: ${actual[shared]!.trim()})` };
  if (actual.length < expected.length) return { line: shared + 1, text: `(a line is missing: ${expected[shared]!.trim()})` };
  return null;
}

/** Whether `source` holds a block written by {@link appendGraph} or by the desktop editor. */
export function hasEmbeddedGraph(source: string): boolean {
  return source.includes(EMBED_BEGIN) && source.includes(EMBED_END);
}

/**
 * Reads the graph out of the block.
 *
 * @throws Error when the source has no block, or the block is damaged
 */
export function extractGraph(source: string): Graph {
  const begin = source.indexOf(EMBED_BEGIN);
  const end = begin < 0 ? -1 : source.indexOf(EMBED_END, begin);
  if (begin < 0 || end < 0) {
    throw new Error("This file has no embedded graph. Only scripts generated by Forgeroom can be imported.");
  }
  let encoded = "";
  for (const line of source.slice(begin + EMBED_BEGIN.length, end).split(/\r?\n/)) {
    const trimmed = line.trim();
    if (trimmed.startsWith("//")) encoded += trimmed.slice(2).trim();
  }
  let json: string;
  try {
    json = fromBase64(encoded);
  } catch (error) {
    throw new Error(`The embedded graph is damaged: ${error instanceof Error ? error.message : String(error)}`);
  }
  const graph = parseGraph(json);
  for (const variable of graph.variables) variable.value = narrowLiteral(variable.value);
  for (const node of graph.nodes) {
    node.x = narrowFloat(node.x);
    node.y = narrowFloat(node.y);
    for (const [pin, literal] of Object.entries(node.literals)) node.literals[pin] = narrowLiteral(literal);
  }
  return graph;
}
