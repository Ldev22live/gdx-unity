import { generateTypeScript, className } from "../../visualscript/codegen";
import { generateJvm, JVM_EXTENSIONS } from "../../visualscript/codegenJvm";
import { extractGraph, findEdit } from "../../visualscript/sourceEmbed";
import {
  defaultValue, Graph, isVec3, parseGraph, replaceGraphContents, serializeGraph,
  VALUE_TYPES, type GraphNode, type Literal, type ValueType,
} from "../../visualscript/graph";
import { createDefaultRegistry, newNode, NODE, PROPERTY_VARIABLE, type NodeType, type PinDef } from "../../visualscript/nodes";
import type { GraphStore } from "../../visualscript/store";
import { connectionProblem, validateGraph, type GraphProblem } from "../../visualscript/validator";
import { h } from "../dom";
import type { EditorModel } from "../EditorModel";

/** One line of `graphs/index.json`, written by `npm run sync-samples`. */
interface GraphEntry {
  path: string;
  name: string;
}

const MAX_UNDO = 50;
/** Where a node added from the palette goes, relative to the top-left of the visible canvas, and the step between neighbours. */
const ADD_ORIGIN = 60;
const ADD_STEP = 24;
const WIRE_COLORS: Record<ValueType | "EXEC", string> = {
  EXEC: "#e8e8e8", FLOAT: "#6cd36c", INTEGER: "#4dd6c0", BOOLEAN: "#d36c6c", STRING: "#e07fd0", VECTOR3: "#e0c24d", ENTITY: "#5aa0ff", OBJECT: "#5aa0ff",
};

/**
 * The Visual Scripting tab (TD-044): a node graph editor in the style of Unreal's Blueprints, for the same `.graph` files
 * the desktop editor edits. Drag from a pin to wire it, drag a node by its title, click a wire to remove it. Edits go
 * straight into the {@link GraphStore} the player uses, so Play runs them without saving. "Generate" turns
 * the graph into a script in TypeScript (web), Java or Kotlin (desktop), and "Import script…" opens the graph embedded in
 * such a script from either editor (TD-045).
 */
export class GraphTab {
  readonly root: HTMLElement;
  private readonly registry = createDefaultRegistry();
  private readonly world = h("div", { class: "world" });
  private readonly wires = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  private readonly viewport = h("div", { class: "viewport", tabindex: "0" });
  private readonly palette = h("div", { class: "palette-list" });
  private readonly search = h("input", { type: "search", placeholder: "Search nodes…" }) as HTMLInputElement;
  private readonly openSelect = h("select", { title: "Open a graph" }) as HTMLSelectElement;
  private readonly nameField = h("input", { type: "text", title: "Graph name", class: "graph-name" }) as HTMLInputElement;
  private readonly problems = h("span", { class: "problems" });
  private readonly variables = h("div", { class: "variables" });
  private readonly code = h("pre", { class: "code" }, "Press Generate to see the script for this graph.");
  private readonly languageSelect = h(
    "select",
    { title: "Language of the generated script" },
    h("option", { value: "ts" }, "TypeScript"),
    h("option", { value: "java" }, "Java"),
    h("option", { value: "kotlin" }, "Kotlin"),
  ) as HTMLSelectElement;
  /** The script shown in the Script box, with the file name to download it under; null when there is none. */
  private generated: { fileName: string; text: string } | null = null;
  private readonly undoButton = h("button", { title: "Undo (Ctrl+Z)" }, "Undo") as HTMLButtonElement;
  private readonly redoButton = h("button", { title: "Redo (Ctrl+Y)" }, "Redo") as HTMLButtonElement;

  private graph: Graph = new Graph("Graph");
  private path = "graphs/Graph.graph";
  private selected: string | null = null;
  private pan = { x: 20, y: 20 };
  private undoStack: string[] = [];
  private redoStack: string[] = [];
  private nodeProblems = new Map<string, string>();
  private added = 0;
  private entries: GraphEntry[] = [];
  private loaded = false;
  private wireDrag: { from: { node: string; pin: string } | null; to: { node: string; pin: string } | null; x: number; y: number } | null = null;

  constructor(
    host: HTMLElement,
    private readonly model: EditorModel,
    private readonly store: GraphStore,
    private readonly setStatus: (message: string, isError?: boolean) => void,
  ) {
    this.wires.setAttribute("class", "wires");
    this.world.append(this.wires);
    this.viewport.append(this.world);
    const toolbar = h(
      "div",
      { class: "gbar" },
      this.button("New", () => this.newGraph(), "Start an empty graph"),
      this.openSelect,
      this.button("Open file…", () => this.openFile(), "Open a .graph file"),
      this.button("Import script…", () => this.importScript(), "Open the graph inside a script generated by Forgeroom (TypeScript, Java or Kotlin, from either editor)"),
      this.button("Save", () => this.download(), "Download the graph as a .graph file"),
      this.undoButton,
      this.redoButton,
      this.nameField,
      this.problems,
      h("span", { class: "spacer" }),
      this.button("Use on selected entity", () => this.assignToSelection(), "Add a Graph Script with this graph to the entity selected in the Viewport tab"),
      this.languageSelect,
      this.button("Generate", () => this.generate(), "Make a script from this graph in the chosen language; Java and Kotlin run in the desktop game, TypeScript in the web player"),
    );
    const side = h(
      "aside",
      { class: "gside" },
      h("h2", {}, "Variables"),
      this.variables,
      h("h2", {}, "Script"),
      h("div", { class: "code-buttons" }, this.button("Copy", () => void this.copyCode()), this.button("Download", () => this.downloadCode())),
      this.code,
    );
    this.root = h("section", { id: "scripting" }, toolbar, h("aside", { class: "palette" }, h("h2", {}, "Nodes"), this.search, this.palette), this.viewport, side);
    this.root.hidden = true;
    host.append(this.root);

    this.buildPalette();
    this.bindEvents();
    this.setGraph(this.graph, this.path, false);
  }

  /** Shows or hides the tab; the list of graphs is read the first time it is shown. */
  setVisible(visible: boolean): void {
    this.root.hidden = !visible;
    if (visible && !this.loaded) {
      this.loaded = true;
      void this.loadIndex();
    }
    if (visible) this.drawWires();
  }

  /** The graph being edited (the one in the store under {@link currentPath}). */
  get current(): Graph {
    return this.graph;
  }

  get currentPath(): string {
    return this.path;
  }

  private async loadIndex(): Promise<void> {
    try {
      const response = await fetch("graphs/index.json");
      if (!response.ok) throw new Error(`graphs/index.json: HTTP ${response.status}`);
      this.entries = (await response.json()) as GraphEntry[];
      this.openSelect.replaceChildren(h("option", { value: "" }, "Open sample…"), ...this.entries.map((entry) => h("option", { value: entry.path }, entry.name)));
      if (this.entries.length > 0 && this.graph.nodes.length === 0) await this.openPath(this.entries[0]!.path);
    } catch (error) {
      this.setStatus(`Could not list the graphs: ${error instanceof Error ? error.message : String(error)}. Run \`npm run sync-samples\`.`, true);
    }
  }

  // ---- Documents ----------------------------------------------------------------------------------------------

  private setGraph(graph: Graph, path: string, record = true): void {
    if (record) this.undoStack = [];
    this.redoStack = [];
    this.graph = graph;
    this.path = path;
    this.store.set(path, graph);
    this.selected = null;
    this.render();
  }

  async openPath(path: string): Promise<void> {
    try {
      const graph = await this.store.load(path);
      this.setGraph(graph, path);
      this.setStatus(`Opened ${path}`);
    } catch (error) {
      this.setStatus(error instanceof Error ? error.message : String(error), true);
    }
  }

  private newGraph(): void {
    const name = window.prompt("Name of the new graph", "My Graph")?.trim();
    if (!name) return;
    const graph = new Graph(name);
    graph.addNode(newNode(this.registry, graph, NODE.beginPlay, 0, 0));
    graph.addNode(newNode(this.registry, graph, NODE.tick, 0, 140));
    const safe = name.replace(/[^A-Za-z0-9 _-]/g, "").trim() || "Graph";
    this.setGraph(graph, `graphs/${safe}.graph`);
    this.setStatus(`New graph ${name}`);
  }

  private openFile(): void {
    const input = h("input", { type: "file", accept: ".graph,application/json" }) as HTMLInputElement;
    input.addEventListener("change", async () => {
      const file = input.files?.[0];
      if (!file) return;
      try {
        const graph = parseGraph(await file.text());
        this.setGraph(graph, `graphs/${file.name}`);
        this.setStatus(`Opened ${file.name}`);
      } catch (error) {
        this.setStatus(`Cannot open ${file.name}: ${error instanceof Error ? error.message : String(error)}`, true);
      }
    });
    input.click();
  }

  private download(): void {
    const found = validateGraph(this.graph, this.registry);
    saveAs(`${this.graph.name || "graph"}.graph`, serializeGraph(this.graph), "application/json");
    this.setStatus(found.length === 0 ? `Saved ${this.graph.name}.graph` : `Saved ${this.graph.name}.graph with ${found.length} problem(s): ${found[0]!.message}`, found.length > 0);
  }

  /** Adds a Graph Script with this graph to the selected entity (or points its existing one here), as one undo step. */
  private assignToSelection(): void {
    const id = this.model.selection;
    if (id === null) {
      this.setStatus("Select an entity in the Viewport tab first", true);
      return;
    }
    const path = this.path;
    this.model.edit("Assign visual script", "scene", (file) => {
      const entity = file.entities.find((item) => item.id === id);
      if (!entity) throw new Error(`Entity ${id} is not in the scene`);
      const script = entity.components.find((component) => component.type === "GraphScriptComponent");
      if (script) script.data["graph"] = path;
      else entity.components.push({ type: "GraphScriptComponent", enabled: true, data: { graph: path } });
    });
    this.setStatus(`${this.model.require(id).name} runs ${path} when the scene plays`);
  }

  private importScript(): void {
    const input = h("input", { type: "file", accept: ".ts,.java,.kt,text/plain" }) as HTMLInputElement;
    input.addEventListener("change", async () => {
      const file = input.files?.[0];
      if (!file) return;
      try {
        const text = await file.text();
        const graph = extractGraph(text);
        const safe = graph.name.replace(/[^A-Za-z0-9 _-]/g, "").trim() || "Graph";
        this.setGraph(graph, `graphs/${safe}.graph`);
        const edit = this.findHandEdit(file.name, text, graph);
        this.setStatus(
          `Imported ${file.name} as ${graph.name}` +
            (edit ? `. The code was edited after it was generated (first change at line ${edit.line}: ${edit.text}); edits to code are not read back, the graph is the one embedded` : ""),
          edit !== null,
        );
      } catch (error) {
        this.setStatus(`Cannot import ${file.name}: ${error instanceof Error ? error.message : String(error)}`, true);
      }
    });
    input.click();
  }

  /** The first line of an imported script that differs from what its graph generates now, or null (also when it cannot be compared). */
  private findHandEdit(fileName: string, text: string, graph: Graph): ReturnType<typeof findEdit> {
    try {
      const lower = fileName.toLowerCase();
      const generated = lower.endsWith(".ts") ? generateTypeScript(graph, this.registry) : generateJvm(graph, this.registry, lower.endsWith(".kt") ? "kotlin" : "java");
      return findEdit(text, generated);
    } catch {
      // The graph cannot be turned into code here (a node with no web code): it is imported all the same
      return null;
    }
  }

  private generate(): void {
    const language = this.languageSelect.value;
    try {
      const source =
        language === "ts" ? generateTypeScript(this.graph, this.registry) : generateJvm(this.graph, this.registry, language === "kotlin" ? "kotlin" : "java");
      const extension = language === "ts" ? ".ts" : JVM_EXTENSIONS[language === "kotlin" ? "kotlin" : "java"];
      this.generated = { fileName: `${className(this.graph)}${extension}`, text: source };
      this.code.textContent = source;
      this.code.classList.remove("error");
      this.setStatus(`Generated ${this.generated.fileName}`);
    } catch (error) {
      this.generated = null;
      this.code.textContent = error instanceof Error ? error.message : String(error);
      this.code.classList.add("error");
      this.setStatus(`Cannot generate code: ${this.code.textContent}`, true);
    }
  }

  private async copyCode(): Promise<void> {
    if (!this.generated) return this.setStatus("Generate the script first", true);
    await navigator.clipboard.writeText(this.generated.text);
    this.setStatus("Copied the script");
  }

  private downloadCode(): void {
    if (!this.generated) return this.setStatus("Generate the script first", true);
    saveAs(this.generated.fileName, this.generated.text, "text/plain");
  }

  // ---- Undo ---------------------------------------------------------------------------------------------------

  /** Call before a change: remembers the graph as it is so Undo can bring it back. */
  private snapshot(): void {
    this.undoStack.push(serializeGraph(this.graph));
    if (this.undoStack.length > MAX_UNDO) this.undoStack.shift();
    this.redoStack = [];
  }

  undo(): void {
    this.restore(this.undoStack, this.redoStack);
  }

  redo(): void {
    this.restore(this.redoStack, this.undoStack);
  }

  private restore(from: string[], to: string[]): void {
    const text = from.pop();
    if (text === undefined) return;
    to.push(serializeGraph(this.graph));
    replaceGraphContents(this.graph, parseGraph(text));
    if (this.selected && !this.graph.node(this.selected)) this.selected = null;
    this.render();
  }

  // ---- Palette ------------------------------------------------------------------------------------------------

  private buildPalette(): void {
    const filter = this.search.value.trim().toLowerCase();
    this.palette.replaceChildren();
    const byCategory = new Map<string, NodeType[]>();
    for (const type of this.registry.all()) {
      if (filter && !type.title.toLowerCase().includes(filter) && !type.category.toLowerCase().includes(filter)) continue;
      byCategory.set(type.category, [...(byCategory.get(type.category) ?? []), type]);
    }
    for (const [category, types] of byCategory) {
      this.palette.append(h("div", { class: "group" }, category));
      for (const type of types) {
        const button = h("button", { class: "node-type", title: `Add ${type.title}` }, type.title) as HTMLButtonElement;
        button.addEventListener("click", () => this.addNode(type.id));
        this.palette.append(button);
      }
    }
  }

  private addNode(typeId: string): void {
    this.snapshot();
    const offset = ADD_ORIGIN + (this.added++ % 8) * ADD_STEP;
    const node = newNode(this.registry, this.graph, typeId, offset - this.pan.x, offset - this.pan.y);
    this.graph.addNode(node);
    this.selected = node.id;
    this.render();
  }

  // ---- Rendering ----------------------------------------------------------------------------------------------

  private render(): void {
    this.nameField.value = this.graph.name;
    this.world.style.transform = `translate(${this.pan.x}px, ${this.pan.y}px)`;
    for (const element of [...this.world.querySelectorAll(".node")]) element.remove();
    const found = validateGraph(this.graph, this.registry);
    this.nodeProblems = new Map();
    for (const problem of found) if (problem.nodeId) this.nodeProblems.set(problem.nodeId, problem.message);
    for (const node of this.graph.nodes) this.world.append(this.renderNode(node));
    this.renderProblems(found);
    this.renderVariables();
    this.undoButton.disabled = this.undoStack.length === 0;
    this.redoButton.disabled = this.redoStack.length === 0;
    this.drawWires();
  }

  private renderProblems(found: GraphProblem[]): void {
    this.problems.textContent = found.length === 0 ? "No problems" : `${found.length} problem(s): ${found[0]!.message}`;
    this.problems.classList.toggle("bad", found.length > 0);
  }

  private renderNode(node: GraphNode): HTMLElement {
    const type = this.registry.get(node.type);
    const element = h("div", { class: "node", "data-node": node.id });
    element.style.left = `${node.x}px`;
    element.style.top = `${node.y}px`;
    element.classList.toggle("selected", node.id === this.selected);
    element.classList.add(type ? type.kind : "unknown");
    const problem = this.nodeProblems.get(node.id);
    if (problem) {
      element.classList.add("bad");
      element.title = problem;
    }
    const title = h("div", { class: "title" }, type?.title ?? node.type);
    element.append(title);
    if (!type) return element;

    for (const property of type.properties) element.append(this.propertyField(node, property));
    const pins = type.pins(node, this.graph);
    const inputs = pins.filter((pin) => pin.input);
    const outputs = pins.filter((pin) => !pin.input);
    const rows = Math.max(inputs.length, outputs.length);
    const body = h("div", { class: "pins" });
    for (let i = 0; i < rows; i++) {
      const row = h("div", { class: "row" }, inputs[i] ? this.pinView(node, inputs[i]!) : h("span"), outputs[i] ? this.pinView(node, outputs[i]!) : h("span"));
      body.append(row);
    }
    element.append(body);
    this.bindNode(element, title, node);
    return element;
  }

  private propertyField(node: GraphNode, property: string): HTMLElement {
    if (property === PROPERTY_VARIABLE) {
      const select = h("select", { title: "Variable" }, ...this.graph.variables.map((variable) => h("option", { value: variable.name }, variable.name))) as HTMLSelectElement;
      select.value = node.properties[property] ?? "";
      if (select.value !== (node.properties[property] ?? "")) select.prepend(h("option", { value: node.properties[property] ?? "" }, node.properties[property] || "(choose)"));
      select.value = node.properties[property] ?? "";
      select.addEventListener("change", () => {
        this.snapshot();
        node.properties[property] = select.value;
        this.render();
      });
      return h("div", { class: "property" }, select);
    }
    const input = h("input", { type: "text", value: node.properties[property] ?? "", placeholder: property }) as HTMLInputElement;
    input.addEventListener("change", () => {
      this.snapshot();
      node.properties[property] = input.value;
      this.render();
    });
    return h("div", { class: "property" }, input);
  }

  private pinView(node: GraphNode, pin: PinDef): HTMLElement {
    const kind = pin.exec ? "EXEC" : pin.type!;
    const dot = h("span", { class: `dot ${pin.exec ? "exec" : "data"}`, "data-node": node.id, "data-pin": pin.id, "data-dir": pin.input ? "in" : "out", title: pin.exec ? "Execution" : pin.type! });
    dot.style.setProperty("--pin", WIRE_COLORS[kind]);
    const label = h("span", { class: "label" }, pin.label);
    const wired = pin.input && this.graph.linksInto(node.id, pin.id).length > 0;
    const parts: (Node | string)[] = pin.input ? [dot, label] : [label, dot];
    if (pin.input && !pin.exec && !wired && pin.type !== "ENTITY" && pin.type !== "OBJECT") parts.splice(2, 0, this.literalField(node, pin));
    if (pin.type === "OBJECT") label.textContent = `${pin.label} (${pin.objectClass ?? "Object"})`;
    if (pin.input && pin.type === "ENTITY" && !wired) parts.splice(2, 0, h("span", { class: "self" }, "self"));
    const view = h("span", { class: `pin ${pin.input ? "in" : "out"}` }, ...parts);
    dot.addEventListener("pointerdown", (event) => this.startWire(event, node.id, pin));
    return view;
  }

  /** The typed-in value of an unwired data input. */
  private literalField(node: GraphNode, pin: PinDef): HTMLElement {
    const type = pin.type!;
    const value = (node.literals[pin.id] ?? defaultValue(type)) as Literal;
    const commit = (next: Literal): void => {
      this.snapshot();
      node.literals[pin.id] = next;
      this.renderProblems(validateGraph(this.graph, this.registry));
    };
    if (type === "BOOLEAN") {
      const box = h("input", { type: "checkbox" }) as HTMLInputElement;
      box.checked = value === true;
      box.addEventListener("change", () => commit(box.checked));
      return box;
    }
    if (type === "VECTOR3" && isVec3(value)) {
      const make = (axis: "x" | "y" | "z"): HTMLInputElement => {
        const input = h("input", { type: "number", step: "any", class: "num small", value: String(value[axis]) }) as HTMLInputElement;
        input.addEventListener("change", () => {
          const current = (node.literals[pin.id] as { x: number; y: number; z: number } | undefined) ?? { x: 0, y: 0, z: 0 };
          commit({ ...current, [axis]: Number(input.value) || 0 });
        });
        return input;
      };
      return h("span", { class: "vec" }, make("x"), make("y"), make("z"));
    }
    if (type === "FLOAT" || type === "INTEGER") {
      const whole = type === "INTEGER";
      const input = h("input", { type: "number", step: whole ? "1" : "any", class: "num", value: String(value) }) as HTMLInputElement;
      input.addEventListener("change", () => {
        const typed = whole ? Math.trunc(Number(input.value) || 0) : Number(input.value) || 0;
        if (whole) (node.integerLiterals ??= new Set()).add(pin.id);
        commit(typed);
      });
      return input;
    }
    const input = h("input", { type: "text", class: "text", value: String(value) }) as HTMLInputElement;
    input.addEventListener("change", () => commit(input.value));
    return input;
  }

  private renderVariables(): void {
    this.variables.replaceChildren();
    for (const variable of this.graph.variables) {
      const remove = h("button", { class: "small", title: "Remove the variable" }, "×") as HTMLButtonElement;
      remove.addEventListener("click", () => {
        this.snapshot();
        this.graph.variables.splice(this.graph.variables.indexOf(variable), 1);
        this.render();
      });
      const row = h("div", { class: "variable" }, h("span", { class: "vname" }, variable.name), h("span", { class: "vtype" }, variable.type));
      if (variable.type !== "ENTITY" && variable.type !== "VECTOR3") {
        const input = h("input", { type: variable.type === "BOOLEAN" ? "checkbox" : variable.type === "FLOAT" ? "number" : "text", step: "any" }) as HTMLInputElement;
        if (variable.type === "BOOLEAN") input.checked = variable.value === true;
        else input.value = String(variable.value ?? "");
        input.addEventListener("change", () => {
          this.snapshot();
          variable.value = variable.type === "BOOLEAN" ? input.checked : variable.type === "FLOAT" ? Number(input.value) || 0 : input.value;
        });
        row.append(input);
      }
      row.append(remove);
      this.variables.append(row);
    }
    const name = h("input", { type: "text", placeholder: "name" }) as HTMLInputElement;
    const type = h("select", {}, ...VALUE_TYPES.filter((t) => t !== "ENTITY").map((t) => h("option", { value: t }, t))) as HTMLSelectElement;
    const add = h("button", {}, "Add") as HTMLButtonElement;
    add.addEventListener("click", () => {
      const variableName = name.value.trim();
      if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(variableName)) return this.setStatus("A variable name uses letters, digits and _, and starts with a letter", true);
      if (this.graph.variable(variableName)) return this.setStatus(`There is already a variable ${variableName}`, true);
      this.snapshot();
      this.graph.variables.push({ name: variableName, type: type.value as ValueType, value: defaultValue(type.value as ValueType) });
      this.render();
    });
    this.variables.append(h("div", { class: "add-variable" }, name, type, add));
  }

  // ---- Wires --------------------------------------------------------------------------------------------------

  /** Centre of a pin's dot in the world's coordinates, or null when it is not drawn. */
  private pinPosition(nodeId: string, pinId: string, direction: "in" | "out"): { x: number; y: number } | null {
    const dot = this.world.querySelector(`.dot[data-node="${CSS.escape(nodeId)}"][data-pin="${CSS.escape(pinId)}"][data-dir="${direction}"]`);
    if (!dot) return null;
    const box = dot.getBoundingClientRect();
    const origin = this.world.getBoundingClientRect();
    return { x: box.left + box.width / 2 - origin.left, y: box.top + box.height / 2 - origin.top };
  }

  private drawWires(): void {
    this.wires.replaceChildren();
    for (const link of this.graph.links) {
      const from = this.pinPosition(link.from, link.fromPin, "out");
      const to = this.pinPosition(link.to, link.toPin, "in");
      if (!from || !to) continue;
      const fromNode = this.graph.node(link.from);
      const pin = fromNode ? this.registry.pin(fromNode, this.graph, link.fromPin) : undefined;
      const path = this.wirePath(from, to, pin?.exec ? WIRE_COLORS.EXEC : WIRE_COLORS[pin?.type ?? "FLOAT"]);
      path.setAttribute("class", "wire");
      path.addEventListener("click", () => {
        this.snapshot();
        this.graph.removeLink(link);
        this.render();
      });
      this.wires.append(path);
    }
    if (this.wireDrag) {
      const { from, to, x, y } = this.wireDrag;
      const known = from ? this.pinPosition(from.node, from.pin, "out") : to ? this.pinPosition(to.node, to.pin, "in") : null;
      if (known) {
        const origin = this.world.getBoundingClientRect();
        const pointer = { x: x - origin.left, y: y - origin.top };
        const path = from ? this.wirePath(known, pointer, "#ffffff") : this.wirePath(pointer, known, "#ffffff");
        path.setAttribute("class", "wire dragging");
        this.wires.append(path);
      }
    }
  }

  private wirePath(from: { x: number; y: number }, to: { x: number; y: number }, color: string): SVGPathElement {
    const path = document.createElementNS("http://www.w3.org/2000/svg", "path");
    const bend = Math.max(40, Math.abs(to.x - from.x) / 2);
    path.setAttribute("d", `M ${from.x} ${from.y} C ${from.x + bend} ${from.y}, ${to.x - bend} ${to.y}, ${to.x} ${to.y}`);
    path.setAttribute("stroke", color);
    return path;
  }

  /** Pressing a pin starts a wire; an input that already has a wire picks it up, so it can be moved to another input. */
  private startWire(event: PointerEvent, nodeId: string, pin: PinDef): void {
    event.preventDefault();
    event.stopPropagation();
    let from: { node: string; pin: string } | null = null;
    let to: { node: string; pin: string } | null = null;
    if (pin.input) {
      const existing = this.graph.linksInto(nodeId, pin.id)[0];
      if (existing) {
        this.snapshot();
        this.graph.removeLink(existing);
        from = { node: existing.from, pin: existing.fromPin };
        this.render();
      } else {
        to = { node: nodeId, pin: pin.id };
      }
    } else {
      from = { node: nodeId, pin: pin.id };
    }
    this.wireDrag = { from, to, x: event.clientX, y: event.clientY };
    const move = (e: PointerEvent): void => {
      if (!this.wireDrag) return;
      this.wireDrag.x = e.clientX;
      this.wireDrag.y = e.clientY;
      this.drawWires();
    };
    const up = (e: PointerEvent): void => {
      window.removeEventListener("pointermove", move);
      window.removeEventListener("pointerup", up);
      const drag = this.wireDrag;
      this.wireDrag = null;
      const hit = document.elementFromPoint(e.clientX, e.clientY)?.closest(".dot") as HTMLElement | null;
      if (drag && hit && this.root.contains(hit)) this.connect(drag.from, drag.to, hit);
      else this.drawWires();
    };
    window.addEventListener("pointermove", move);
    window.addEventListener("pointerup", up);
  }

  private connect(from: { node: string; pin: string } | null, to: { node: string; pin: string } | null, hit: HTMLElement): void {
    const other = { node: hit.dataset["node"]!, pin: hit.dataset["pin"]! };
    const output = from ?? (hit.dataset["dir"] === "out" ? other : null);
    const input = to ?? (hit.dataset["dir"] === "in" ? other : null);
    if (!output || !input) {
      this.setStatus("Wires go from an output to an input", true);
      this.render();
      return;
    }
    const fromNode = this.graph.requireNode(output.node);
    const toNode = this.graph.requireNode(input.node);
    const fromPin = this.registry.pin(fromNode, this.graph, output.pin);
    const toPin = this.registry.pin(toNode, this.graph, input.pin);
    const problem = fromPin && toPin ? connectionProblem(fromPin, toPin) : "That pin does not exist";
    if (problem) {
      this.setStatus(problem, true);
      this.render();
      return;
    }
    this.snapshot();
    // A data input takes one wire and an execution output feeds one node: a new wire replaces the old one
    for (const old of [...this.graph.links]) {
      const sameInput = !fromPin!.exec && old.to === input.node && old.toPin === input.pin;
      const sameOutput = fromPin!.exec && old.from === output.node && old.fromPin === output.pin;
      if (sameInput || sameOutput) this.graph.removeLink(old);
    }
    this.graph.addLink({ from: output.node, fromPin: output.pin, to: input.node, toPin: input.pin });
    this.render();
  }

  // ---- Interaction --------------------------------------------------------------------------------------------

  private bindNode(element: HTMLElement, title: HTMLElement, node: GraphNode): void {
    element.addEventListener("pointerdown", () => {
      this.viewport.focus({ preventScroll: true });
      if (this.selected === node.id) return;
      this.selected = node.id;
      for (const other of this.world.querySelectorAll(".node")) other.classList.toggle("selected", other === element);
    });
    title.addEventListener("pointerdown", (event) => {
      event.preventDefault();
      const startX = event.clientX;
      const startY = event.clientY;
      const originX = node.x;
      const originY = node.y;
      let moved = false;
      const move = (e: PointerEvent): void => {
        if (!moved) {
          moved = true;
          this.snapshot();
        }
        node.x = Math.round(originX + e.clientX - startX);
        node.y = Math.round(originY + e.clientY - startY);
        element.style.left = `${node.x}px`;
        element.style.top = `${node.y}px`;
        this.drawWires();
      };
      const up = (): void => {
        window.removeEventListener("pointermove", move);
        window.removeEventListener("pointerup", up);
        if (moved) this.undoButton.disabled = false;
      };
      window.addEventListener("pointermove", move);
      window.addEventListener("pointerup", up);
    });
  }

  private bindEvents(): void {
    this.search.addEventListener("input", () => this.buildPalette());
    this.nameField.addEventListener("change", () => {
      this.snapshot();
      this.graph.name = this.nameField.value.trim() || "Graph";
      this.render();
    });
    this.openSelect.addEventListener("change", () => {
      if (this.openSelect.value) void this.openPath(this.openSelect.value);
      this.openSelect.value = "";
    });
    this.undoButton.addEventListener("click", () => this.undo());
    this.redoButton.addEventListener("click", () => this.redo());
    this.viewport.addEventListener("pointerdown", (event) => {
      if (event.target !== this.viewport && event.target !== this.world && event.target !== this.wires) return;
      this.selected = null;
      for (const element of this.world.querySelectorAll(".node.selected")) element.classList.remove("selected");
      const startX = event.clientX - this.pan.x;
      const startY = event.clientY - this.pan.y;
      const move = (e: PointerEvent): void => {
        this.pan = { x: e.clientX - startX, y: e.clientY - startY };
        this.world.style.transform = `translate(${this.pan.x}px, ${this.pan.y}px)`;
      };
      const up = (): void => {
        window.removeEventListener("pointermove", move);
        window.removeEventListener("pointerup", up);
      };
      window.addEventListener("pointermove", move);
      window.addEventListener("pointerup", up);
    });
    this.viewport.addEventListener("keydown", (event) => {
      const typing = event.target instanceof HTMLInputElement || event.target instanceof HTMLSelectElement;
      if (typing) return;
      if ((event.key === "Delete" || event.key === "Backspace") && this.selected) {
        event.preventDefault();
        this.snapshot();
        this.graph.removeNode(this.selected);
        this.selected = null;
        this.render();
      } else if (event.ctrlKey && event.key.toLowerCase() === "z") {
        event.preventDefault();
        if (event.shiftKey) this.redo();
        else this.undo();
      } else if (event.ctrlKey && event.key.toLowerCase() === "y") {
        event.preventDefault();
        this.redo();
      }
    });
  }

  private button(label: string, action: () => void, title = ""): HTMLButtonElement {
    const button = h("button", title ? { title } : {}, label) as HTMLButtonElement;
    button.addEventListener("click", action);
    return button;
  }
}

/** Offers {@code text} to the user as a file download. */
function saveAs(name: string, text: string, type: string): void {
  const link = h("a", { download: name }) as HTMLAnchorElement;
  link.href = URL.createObjectURL(new Blob([text], { type }));
  link.click();
  URL.revokeObjectURL(link.href);
}

